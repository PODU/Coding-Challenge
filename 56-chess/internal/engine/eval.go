func pstValue(pt PieceType, sq Square, c Color) int {
	var table *[64]int
	switch pt {
	case Pawn:
		table = &pstPawn
	case Knight:
		table = &pstKnight
	case Bishop:
		table = &pstBishop
	case Rook:
		table = &pstRook
	case Queen:
		table = &pstQueen
	case King:
		table = &pstKing
	default:
		return 0
	}
	row := sq.Rank()
	if c == White {
		row = 7 - row
	}
	return table[row*8+sq.File()]
}

// Evaluate returns material plus piece-square bonuses in centipawns. Positive
// means the side to move is better.
func (b *Board) Evaluate() int {
	score := 0 // from White's perspective
	for sq := Square(0); sq < 128; sq++ {
		if !sq.OnBoard() {
			sq += 7
			continue
		}
		p := b.squares[sq]
		if p == Empty {
			continue
		}
		pt := p.Type()
		v := pieceValue[pt] + pstValue(pt, sq, p.Color())
		if p.Color() == White {
			score += v
		} else {
			score -= v
		}
	}
	if b.side == White {
		return score
	}
	return -score
}
