// Package analysis answers questions about a scanned tree: how old things
// are, which files are largest, what looks reclaimable, and what the user
// has staged for removal. None of it touches the filesystem.
package analysis

import (
	"path/filepath"
	"sort"
	"strings"
	"time"

	"ccdisk/internal/scan"
)

type Band int

const (
	Fresh  Band = iota // under 1 month
	Recent             // under 1 year
	Old                // 1 year or more
)

var BandNames = []string{"< 1 month", "< 1 year", "> 1 year"}

const (
	Month = 30 * 24 * time.Hour
	Year  = 365 * 24 * time.Hour
)

// AgeOf is the time that counts for a node: its own mtime for files, its
// newest descendant's for directories.
func AgeOf(n *scan.Node) time.Time {
	if n.Kind == scan.Dir {
		return n.Newest
	}
	return n.ModTime
}

func BandOf(t, now time.Time) Band {
	switch age := now.Sub(t); {
	case age < Month:
		return Fresh
	case age < Year:
		return Recent
	default:
		return Old
	}
}

type Filter struct {
	MinSize int64         // in the chosen measure
	MinAge  time.Duration // not modified for at least this long
	Measure scan.Measure
	Now     time.Time
}

// Largest lists regular files under scope, biggest first. A second name of
// a hard-linked file has size 0 (its space is counted under the first), so
// it sinks to the bottom rather than appearing twice at the top.
func Largest(scope *scan.Node, f Filter, limit int) []*scan.Node {
	var out []*scan.Node
	var walk func(n *scan.Node)
	walk = func(n *scan.Node) {
		if n.Kind == scan.File {
			if n.Size(f.Measure) >= f.MinSize && (f.MinAge == 0 || f.Now.Sub(n.ModTime) >= f.MinAge) {
				out = append(out, n)
			}
			return
		}
		for _, c := range n.Children {
			walk(c)
		}
	}
	walk(scope)
	sort.SliceStable(out, func(i, j int) bool {
		si, sj := out[i].Size(f.Measure), out[j].Size(f.Measure)
		if si != sj {
			return si > sj
		}
		return out[i].Path() < out[j].Path()
	})
	if limit > 0 && len(out) > limit {
		out = out[:limit]
	}
	return out
}

// LargestChildren is a directory's children, biggest first.
func LargestChildren(n *scan.Node, m scan.Measure) []*scan.Node {
	out := append([]*scan.Node(nil), n.Children...)
	sort.SliceStable(out, func(i, j int) bool { return out[i].Size(m) > out[j].Size(m) })
	return out
}

type Category string

const (
	Cache Category = "cache"
	Build Category = "build output"
)

// Build output: regenerated by a build or package install.
var buildDirs = []string{"node_modules", "target", "build", "dist", ".next", ".nuxt",
	"__pycache__", ".pytest_cache", ".mypy_cache", ".tox", ".parcel-cache", ".turbo"}

// Caches, as path suffixes. Matched case-insensitively.
var cacheSuffixes = [][]string{
	{".cache"}, {".npm"}, {"Library", "Caches"}, {".gradle", "caches"},
	{"AppData", "Local", "Temp"}, {"AppData", "Local", "npm-cache"},
	{"AppData", "Local", "pip", "cache"}, {"AppData", "Local", "go-build"},
	{".cargo", "registry", "cache"}, {"Library", "Developer", "Xcode", "DerivedData"},
}

// Classify reports whether a directory looks safe to regenerate.
func Classify(n *scan.Node) (Category, bool) {
	if n.Kind != scan.Dir {
		return "", false
	}
	for _, d := range buildDirs {
		if strings.EqualFold(n.Name, d) {
			return Build, true
		}
	}
	last := n.Name
	if n.Parent == nil {
		last = filepath.Base(n.Name)
	}
	var parts []string // the full path's components, only built when needed
	for _, suf := range cacheSuffixes {
		if !strings.EqualFold(last, suf[len(suf)-1]) {
			continue
		}
		if parts == nil {
			parts = strings.Split(filepath.ToSlash(n.Path()), "/")
		}
		if len(parts) < len(suf) {
			continue
		}
		ok := true
		for i := range suf {
			if !strings.EqualFold(parts[len(parts)-len(suf)+i], suf[i]) {
				ok = false
				break
			}
		}
		if ok {
			return Cache, true
		}
	}
	return "", false
}

type Candidate struct {
	Node     *scan.Node
	Category Category
}

// Reclaimable lists the outermost matching directories under scope. Matches
// nested inside another (node_modules inside node_modules) are not listed
// again, so the total is a plain sum.
func Reclaimable(scope *scan.Node) []Candidate {
	var out []Candidate
	var walk func(n *scan.Node)
	walk = func(n *scan.Node) {
		if c, ok := Classify(n); ok && n != scope {
			out = append(out, Candidate{n, c})
			return
		}
		for _, ch := range n.Children {
			walk(ch)
		}
	}
	walk(scope)
	return out
}

// IsReclaimable reports whether n is, or is inside, a candidate.
func IsReclaimable(n *scan.Node) bool {
	for p := n; p != nil; p = p.Parent {
		if _, ok := Classify(p); ok {
			return true
		}
	}
	return false
}

func ReclaimableTotal(cs []Candidate, m scan.Measure) int64 {
	var t int64
	for _, c := range cs {
		t += c.Node.Size(m)
	}
	return t
}
